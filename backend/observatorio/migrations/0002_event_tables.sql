CREATE TABLE IF NOT EXISTS observatorio.event_versions (
    event_id TEXT NOT NULL,
    updated BIGINT NOT NULL,
    payload_hash TEXT NOT NULL,
    time BIGINT,
    time_utc TIMESTAMPTZ,
    updated_utc TIMESTAMPTZ NOT NULL,
    mag DOUBLE PRECISION,
    mag_type TEXT,
    place TEXT,
    status TEXT,
    tsunami INTEGER,
    sig INTEGER,
    net TEXT,
    code TEXT,
    ids TEXT,
    sources TEXT,
    types TEXT,
    nst INTEGER,
    dmin DOUBLE PRECISION,
    rms DOUBLE PRECISION,
    gap DOUBLE PRECISION,
    mag_error DOUBLE PRECISION,
    mag_nst INTEGER,
    depth_error DOUBLE PRECISION,
    horizontal_error DOUBLE PRECISION,
    event_type TEXT,
    longitude DOUBLE PRECISION NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    depth DOUBLE PRECISION NOT NULL,
    original_feature JSONB NOT NULL,
    source TEXT NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL,
    mode TEXT NOT NULL,
    kafka_topic TEXT NOT NULL,
    kafka_partition INTEGER NOT NULL,
    kafka_offset BIGINT NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (event_id, updated)
);

CREATE INDEX IF NOT EXISTS idx_event_versions_time_utc ON observatorio.event_versions(time_utc);

CREATE TABLE IF NOT EXISTS observatorio.current_events (
    event_id TEXT PRIMARY KEY,
    updated BIGINT NOT NULL,
    payload_hash TEXT NOT NULL,
    time BIGINT,
    time_utc TIMESTAMPTZ,
    updated_utc TIMESTAMPTZ NOT NULL,
    mag DOUBLE PRECISION,
    mag_type TEXT,
    place TEXT,
    status TEXT,
    tsunami INTEGER,
    sig INTEGER,
    net TEXT,
    code TEXT,
    ids TEXT,
    sources TEXT,
    types TEXT,
    nst INTEGER,
    dmin DOUBLE PRECISION,
    rms DOUBLE PRECISION,
    gap DOUBLE PRECISION,
    mag_error DOUBLE PRECISION,
    mag_nst INTEGER,
    depth_error DOUBLE PRECISION,
    horizontal_error DOUBLE PRECISION,
    event_type TEXT,
    longitude DOUBLE PRECISION NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    depth DOUBLE PRECISION NOT NULL,
    original_feature JSONB NOT NULL,
    source TEXT NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL,
    mode TEXT NOT NULL,
    kafka_topic TEXT NOT NULL,
    kafka_partition INTEGER NOT NULL,
    kafka_offset BIGINT NOT NULL,
    last_processed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS idx_current_events_time_utc ON observatorio.current_events(time_utc);
CREATE INDEX IF NOT EXISTS idx_current_events_updated ON observatorio.current_events(updated);

CREATE TABLE IF NOT EXISTS observatorio.quarantine_records (
    id BIGSERIAL PRIMARY KEY,
    kafka_topic TEXT NOT NULL,
    kafka_partition INTEGER NOT NULL,
    kafka_offset BIGINT NOT NULL,
    raw_payload BYTEA NOT NULL,
    rejection_reason TEXT NOT NULL,
    decoded_envelope JSONB,
    quarantined_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_quarantine_kafka_record UNIQUE (kafka_topic, kafka_partition, kafka_offset)
);
